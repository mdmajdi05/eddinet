import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const stockImageRoot = path.join(projectRoot, "public", "images", "stock");
const stockRegistryPath = path.join(projectRoot, "data", "stock-images.ts");
const sourceDirectories = ["app", "components", "data"].map((directory) =>
  path.join(projectRoot, directory),
);
const sourceExtensions = new Set([".ts", ".tsx", ".js", ".jsx", ".css", ".mjs"]);
const remoteImagePattern = /https?:\/\/images\.unsplash\.com\/(photo-[a-zA-Z0-9_-]+)(?:\?[^\s"'`\\)\]}]*)?/g;
const maxEdge = 1600;
const quality = 82;
const concurrency = 4;
const dryRun = process.argv.includes("--dry-run");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nestedFiles = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      if (entry.isDirectory()) return walk(entryPath);
      return entry.isFile() ? [entryPath] : [];
    }),
  );

  return nestedFiles.flat();
}

async function collectSourceFiles() {
  const files = (await Promise.all(sourceDirectories.map(walk))).flat().filter(
    (file) =>
      sourceExtensions.has(path.extname(file).toLowerCase()) &&
      file !== stockRegistryPath,
  );
  const references = new Map();

  for (const file of files) {
    const content = await readFile(file, "utf8");
    for (const match of content.matchAll(remoteImagePattern)) {
      references.set(match[0], match[1]);
    }
  }

  return { files, references };
}

async function fetchWithRetry(url) {
  let lastError;

  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const response = await fetch(url, {
        headers: {
          Accept: "image/avif,image/webp,image/jpeg,*/*;q=0.8",
          "User-Agent": "Eddinet image migration/1.0",
        },
        signal: AbortSignal.timeout(30_000),
      });

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}`);
      }

      const contentType = response.headers.get("content-type") ?? "";
      if (!contentType.startsWith("image/")) {
        throw new Error(`Unexpected content type: ${contentType || "unknown"}`);
      }

      return Buffer.from(await response.arrayBuffer());
    } catch (error) {
      lastError = error;
      if (attempt < 3) {
        await new Promise((resolve) => setTimeout(resolve, attempt * 750));
      }
    }
  }

  throw lastError instanceof Error ? lastError : new Error("Image download failed.");
}

async function downloadImage(photoId) {
  const targetPath = path.join(stockImageRoot, `${photoId}.webp`);

  try {
    const targetStats = await stat(targetPath);
    if (targetStats.isFile() && targetStats.size > 0) {
      return {
        sourceUrl: `https://images.unsplash.com/${photoId}`,
        output: await readFile(targetPath),
        reused: true,
      };
    }
  } catch {
    // The image will be downloaded below.
  }

  const sourceUrl = new URL(`https://images.unsplash.com/${photoId}`);
  sourceUrl.searchParams.set("auto", "format");
  sourceUrl.searchParams.set("fit", "max");
  sourceUrl.searchParams.set("w", String(maxEdge));
  sourceUrl.searchParams.set("q", String(Math.max(quality + 3, 85)));

  const input = await fetchWithRetry(sourceUrl);
  const output = await sharp(input, { failOn: "warning" })
    .rotate()
    .resize({
      width: maxEdge,
      height: maxEdge,
      fit: "inside",
      withoutEnlargement: true,
    })
    .webp({
      quality,
      alphaQuality: 90,
      effort: 6,
      smartSubsample: true,
    })
    .toBuffer();

  return {
    sourceUrl: `https://images.unsplash.com/${photoId}`,
    output,
    reused: false,
  };
}

async function mapWithConcurrency(items, concurrencyLimit, task) {
  const results = new Array(items.length);
  let nextIndex = 0;

  async function worker() {
    while (nextIndex < items.length) {
      const currentIndex = nextIndex;
      nextIndex += 1;
      results[currentIndex] = await task(items[currentIndex], currentIndex);
    }
  }

  await Promise.all(
    Array.from({ length: Math.min(concurrencyLimit, items.length) }, () => worker()),
  );
  return results;
}

function createRegistry(entries) {
  const lines = [
    "/**",
    " * AUTO-GENERATED by scripts/download-remote-images.mjs.",
    " * Do not edit by hand. Run `npm run images:download` after adding remote code images.",
    " */",
    "",
    "export const stockImages = {",
  ];

  for (const [photoId, sourceUrl] of [...entries].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  "${photoId}": {`);
    lines.push(`    src: "/images/stock/${photoId}.webp",`);
    lines.push(`    sourceUrl: "${sourceUrl}",`);
    lines.push("  },");
  }

  lines.push(
    "} as const;",
    "",
    "export type StockImageKey = keyof typeof stockImages;",
    "",
    "export function stockImageSrc(key: StockImageKey): string {",
    "  return stockImages[key].src;",
    "}",
    "",
  );

  return lines.join("\n");
}

function addRegistryImport(content) {
  if (/from\s+["']@\/data\/stock-images["']/.test(content)) return content;
  return `import { stockImageSrc } from "@/data/stock-images";\n\n${content}`;
}

async function main() {
  const { files, references } = await collectSourceFiles();
  const photoIds = [...new Set(references.values())].sort();
  console.log(
    `Found ${references.size} remote image links (${photoIds.length} unique images) in ${files.length} source files.`,
  );

  if (photoIds.length === 0) {
    console.log("No remote code images need downloading.");
    return;
  }

  if (!dryRun) {
    await mkdir(stockImageRoot, { recursive: true });
  }

  let downloadedBytes = 0;
  const downloads = await mapWithConcurrency(photoIds, concurrency, async (photoId) => {
    const { sourceUrl, output, reused } = await downloadImage(photoId);
    downloadedBytes += output.length;
    if (!dryRun && !reused) {
      await writeFile(path.join(stockImageRoot, `${photoId}.webp`), output);
    }
    const action = reused ? "Reused" : dryRun ? "Checked" : "Downloaded";
    console.log(`${action} ${photoId} (${(output.length / 1024).toFixed(1)} KB)`);
    return [photoId, sourceUrl];
  });

  if (dryRun) {
    console.log(`Dry run complete. Estimated output: ${(downloadedBytes / 1024 / 1024).toFixed(2)} MB.`);
    return;
  }

  const uniqueSources = new Map(downloads);
  await writeFile(stockRegistryPath, createRegistry(uniqueSources), "utf8");

  let changedFiles = 0;
  let changedReferences = 0;
  for (const file of files) {
    let content = await readFile(file, "utf8");
    const originalContent = content;

    for (const [url, photoId] of references) {
      const replacement = `stockImageSrc("${photoId}")`;
      let occurrences = 0;

      // Replace the complete quoted URL, not just the URL characters. This
      // prevents generating an invalid string such as \"stockImageSrc(...)\".
      for (const quotedUrl of [`"${url}"`, `'${url}'`, `\`${url}\``]) {
        const count = content.split(quotedUrl).length - 1;
        if (count > 0) {
          content = content.replaceAll(quotedUrl, replacement);
          occurrences += count;
        }
      }

      if (occurrences === 0 && content.includes(url)) {
        // Fallback for an unquoted URL in a non-string image expression.
        occurrences = content.split(url).length - 1;
        content = content.replaceAll(url, replacement);
      }

      changedReferences += occurrences;
    }

    if (content !== originalContent) {
      content = addRegistryImport(content);
      await writeFile(file, content, "utf8");
      changedFiles += 1;
    }
  }

  console.log(`Created registry: ${path.relative(projectRoot, stockRegistryPath)}`);
  console.log(`Updated ${changedReferences} references in ${changedFiles} files.`);
  console.log(`Local stock image total: ${(downloadedBytes / 1024 / 1024).toFixed(2)} MB.`);
}

main().catch((error) => {
  console.error(
    `Remote image download failed: ${error instanceof Error ? error.message : error}`,
  );
  process.exitCode = 1;
});
